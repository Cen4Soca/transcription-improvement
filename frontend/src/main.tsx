import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import { Amplify } from 'aws-amplify'

/**
 * ランタイム設定を読み込み、Amplify を初期化してからアプリを起動する。
 *
 * aws-config.json は CDK デプロイ時に生成され、S3 に配置される。
 * Cognito domain などデプロイ環境に依存する値を含む。
 * .env の値はフォールバックとして使用される。
 */
async function bootstrap() {
  let userPoolId = import.meta.env.VITE_USER_POOL_ID as string
  let userPoolClientId = import.meta.env.VITE_USER_POOL_CLIENT_ID as string
  let apiEndpoint = import.meta.env.VITE_API_ENDPOINT as string || import.meta.env.VITE_API_BASE_URL as string || ''

  // Try to load runtime config (generated by CDK)
  try {
    const response = await fetch(`${import.meta.env.BASE_URL}aws-config.json`)
    if (response.ok) {
      const config = await response.json()
      userPoolId = config.userPoolId || userPoolId
      userPoolClientId = config.userPoolClientId || userPoolClientId
      apiEndpoint = config.apiEndpoint || apiEndpoint
    }
  } catch {
    // Fall back to .env values
  }

  // Store apiEndpoint globally so other modules can access it at runtime
  ;(window as unknown as Record<string, string>).__API_ENDPOINT__ = apiEndpoint

  Amplify.configure({
    Auth: {
      Cognito: {
        userPoolId,
        userPoolClientId,
      },
    },
  })

  // Dynamic import to ensure Amplify is configured before React renders
  const { default: App } = await import('./App.tsx')

  createRoot(document.getElementById('root')!).render(
    <StrictMode>
      <App />
    </StrictMode>,
  )
}

bootstrap()
