#!/bin/bash

set -e

# Set AWS Profile
export AWS_DEFAULT_PROFILE=xxxxx
export AWS_PROFILE=xxxxx

echo "================================"
echo " TRANSCRIPTION IMPROVEMENT      "
echo "           DEPLOY               "
echo "================================"

# Set Node.js memory limit to 1.5GB (1536MB)
export NODE_OPTIONS="--max-old-space-size=1536"

# Process command arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        -c|--cdk-context)
            cdk_context_path="$2"
            shift 2
            ;;
        -h|--help)
            echo "-c, --cdk-context    ... Path to the cdk.json file"
            echo "-h, --help          ... Show this message"
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            exit 1
            ;;
    esac
done

# Check if the file exists
if [[ -n "$cdk_context_path" && ! -f "$cdk_context_path" ]]; then
    echo "Error: CDK context file not found: $cdk_context_path"
    exit 1
fi

pushd /tmp

# Delete the repository in /tmp if it exists
rm -rf transcription-improvement

# Clone transcription-improvement
git clone --depth 1 https://github.com/Cen4Soca/transcription-improvement
pushd transcription-improvement

# If cdk.json is specified, overwrite it
if [[ -n "$cdk_context_path" ]]; then
    echo "Overwrite the cdk.json by $cdk_context_path"
    cp -f $cdk_context_path infra/cdk.json
fi

# Build the frontend so the CDK BucketDeployment (../frontend/dist) picks up
# the latest source. Without this step, cdk deploy re-uploads a stale dist and
# frontend changes never reach S3/CloudFront.
#
# Remove the node_modules copied in from the source tree, then do ONE clean
# install. We do NOT use `npm ci`: eslint-plugin-react@7.37.5 peers eslint <=9.7
# while the project is on eslint@10, so `npm ci` always fails ERESOLVE and, worse,
# leaves node_modules half-deleted (tsc goes missing) which makes a following
# `npm install` think it is "up to date" and skip the repair. A single
# `npm install --legacy-peer-deps` against the kept lockfile resolves cleanly.
# The eslint packages are lint-only and do not affect `vite build`.
# Derive the SPA base path from the CDK context (infra/cdk.json). On the shared
# GenU CloudFront distribution the app is served under /{basePath}/, and the S3
# origin has NO originPath, so the browser requests /{basePath}/assets/... .
# The frontend must therefore be built with Vite base=/{basePath}/ (via
# VITE_BASE_PATH). Without this the HTML references /assets/... (base '/'), those
# requests miss the /{basePath}/* behavior, fall through to the co-hosted app,
# and the JS never loads -> blank screen.
# Read SPA/runtime values from the CDK context (infra/cdk.json). The frontend is
# built from a fresh `git clone` which does NOT contain .env.production (it is
# gitignored), so every VITE_* value the build relies on MUST be injected here
# from cdk.json. VITE_API_ENDPOINT is intentionally omitted: it is supplied at
# runtime via aws-config.json (generated by the CDK deploy), with the build-time
# value only acting as a fallback.
cdk_ctx() {
    node -e "try{process.stdout.write((require('./infra/cdk.json').context['$1'])||'')}catch(e){}"
}
base_path=$(cdk_ctx basePath)
user_pool_id=$(cdk_ctx cognitoUserPoolId)
user_pool_client_id=$(cdk_ctx cognitoUserPoolClientId)
cognito_domain=$(cdk_ctx cognitoDomain)
echo "SPA basePath from cdk.json: '${base_path}'"
echo "Cognito UserPoolId from cdk.json: '${user_pool_id}'"

echo "--------------------------"
echo "   BUILD FRONTEND (dist)  "
echo "--------------------------"
pushd frontend
rm -rf node_modules
npm install --legacy-peer-deps
VITE_BASE_PATH="$base_path" \
VITE_USER_POOL_ID="$user_pool_id" \
VITE_USER_POOL_CLIENT_ID="$user_pool_client_id" \
VITE_COGNITO_DOMAIN="$cognito_domain" \
    npm run build

# --- Fail-safe: verify the built HTML references assets under the expected base ---
# A base-path mismatch (e.g. built with base '/' while served under /{basePath}/)
# produces a blank screen in production because the browser requests /assets/...
# which 404s to the SPA fallback and loads HTML where JS/CSS is expected.
# Fail the deploy here rather than shipping a broken bundle.
if [[ -n "$base_path" ]]; then
    expected_prefix="/${base_path}/assets/"
else
    expected_prefix="/assets/"
fi
if ! grep -q "src=\"${expected_prefix}" dist/index.html; then
    echo "ERROR: dist/index.html does not reference assets under '${expected_prefix}'." >&2
    echo "       The frontend base path is likely wrong (check cdk.json basePath / VITE_BASE_PATH)." >&2
    echo "       Aborting deploy to avoid shipping a blank-screen bundle." >&2
    grep -oE '(src|href)="[^"]*assets[^"]*"' dist/index.html >&2 || true
    exit 1
fi
# When a base path IS expected, also ensure no stray root-relative asset refs leak in.
if [[ -n "$base_path" ]] && grep -qE '(src|href)="/assets/' dist/index.html; then
    echo "ERROR: dist/index.html contains root-relative '/assets/...' references while a base path is set." >&2
    echo "       This indicates an inconsistent build. Aborting deploy." >&2
    exit 1
fi
echo "Frontend asset base path verified: '${expected_prefix}'"
popd

# Install backend dependencies. The CDK NodejsFunction bundles each handler by
# running `npx --no-install esbuild` inside the backend directory, so backend
# MUST have node_modules with the esbuild version required by its package.json.
# Without this step bundling fails with:
#   npx canceled due to missing packages and no YES option: ["esbuild@..."]
echo "--------------------------"
echo "   INSTALL BACKEND DEPS    "
echo "--------------------------"
pushd backend
npm install
popd

# Requirements Install
cd infra
rm -rf node_modules package-lock.json
npm install

# CDK Bootstrap
npx cdk bootstrap

# Check diff
npx cdk diff --all

# Deploy
npx cdk deploy --all --require-approval never
